-- FunEarnEzz setup 1/4: reset app objects and create tables.
-- WARNING: destructive. Use only in a dedicated FunEarnEzz Supabase project.

-- RESET SCOPE: this script intentionally replaces only the FunEarnEzz tables/RPCs
-- listed below. Run ONLY in a Supabase project dedicated to FunEarnEzz.
-- Existing rows in these tables and Auth users created by this app are permanently removed.
do $reset_funearnezz$
declare
  f record;
begin
  for f in
    select p.proname, pg_catalog.oidvectortypes(p.proargtypes) as args
    from pg_catalog.pg_proc p
    join pg_catalog.pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public'
      and p.prokind = 'f'
      and p.proname in (
        'create_withdrawal',
        'create_robux_request',
        'review_submission',
        'review_withdrawal',
        'review_robux_request',
        'admin_adjust_balance'
      )
  loop
    execute format('drop function if exists public.%I(%s) cascade', f.proname, f.args);
  end loop;
end;
$reset_funearnezz$;

drop table if exists
  public.submissions,
  public.withdrawals,
  public.robux_requests,
  public.wallet_transactions,
  public.audit_logs,
  public.settings,
  public.jobs,
  public.profiles
cascade;

-- The Worker generates exactly this synthetic email domain for username-only accounts.
-- This cleanup is project-scoped; do not run in a project shared by other apps.
delete from auth.users
where lower(email) like '%@users.funearnezz.invalid';

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null,
  role text not null default 'user' check (role in ('user','admin')),
  balance numeric(14,2) not null default 0 check (balance >= 0),
  reserved_balance numeric(14,2) not null default 0 check (reserved_balance >= 0),
  disabled boolean not null default false,
  created_at timestamptz not null default now()
);
create unique index if not exists profiles_username_lower_uq on public.profiles (lower(username));

create table if not exists public.jobs (
  id bigint generated by default as identity primary key,
  title text not null check (length(trim(title)) between 1 and 160),
  description text not null default '',
  reward numeric(14,2) not null default 0 check (reward >= 0),
  status text not null default 'active' check (status in ('active','paused','archived')),
  created_at timestamptz not null default now()
);

create table if not exists public.submissions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  job_id bigint not null references public.jobs(id) on delete restrict,
  note text not null default '',
  proof_url text,
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  review_note text,
  reviewed_at timestamptz,
  created_at timestamptz not null default now()
);
create index if not exists submissions_user_created_idx on public.submissions(user_id, created_at desc);
create index if not exists submissions_status_created_idx on public.submissions(status, created_at desc);

create table if not exists public.withdrawals (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  amount numeric(14,2) not null check (amount > 0),
  method text not null,
  destination text not null,
  status text not null default 'pending' check (status in ('pending','paid','rejected')),
  review_note text,
  reviewed_at timestamptz,
  created_at timestamptz not null default now()
);
create index if not exists withdrawals_user_created_idx on public.withdrawals(user_id, created_at desc);
create index if not exists withdrawals_status_created_idx on public.withdrawals(status, created_at desc);

create table if not exists public.robux_requests (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  method text not null check (method in ('gamepass','username')),
  robux integer not null check (robux > 0),
  username text not null,
  gamepass_url text not null default '',
  rate numeric(14,2) not null check (rate > 0),
  cost numeric(14,2) not null check (cost > 0),
  status text not null default 'pending' check (status in ('pending','completed','rejected')),
  review_note text,
  reviewed_at timestamptz,
  created_at timestamptz not null default now()
);
create index if not exists robux_user_created_idx on public.robux_requests(user_id, created_at desc);
create index if not exists robux_status_created_idx on public.robux_requests(status, created_at desc);

create table if not exists public.wallet_transactions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  amount numeric(14,2) not null default 0,
  type text not null,
  status text not null default 'posted',
  reason text not null default '',
  reference_type text,
  reference_id text,
  created_at timestamptz not null default now()
);
create index if not exists wallet_transactions_user_created_idx on public.wallet_transactions(user_id, created_at desc);

create table if not exists public.settings (
  key text primary key,
  value jsonb not null default 'null'::jsonb,
  updated_at timestamptz not null default now()
);

insert into public.settings(key,value) values
  ('robuxMin','10'::jsonb),
  ('gamepassRate','170'::jsonb),
  ('usernameRate','230'::jsonb)
on conflict (key) do nothing;
create table if not exists public.audit_logs (
  id bigint generated by default as identity primary key,
  actor_id uuid references public.profiles(id) on delete set null,
  action text not null,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists audit_logs_created_idx on public.audit_logs(created_at desc);
