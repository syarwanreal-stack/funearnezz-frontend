-- Additive security audit table for login/registration IP logging.
-- Does not alter users, balances, withdrawals, or existing transaction history.
CREATE TABLE IF NOT EXISTS public.login_security_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  event text NOT NULL CHECK (event IN ('login', 'register')),
  ip_address text,
  user_agent text,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS login_security_events_user_ip_idx
  ON public.login_security_events (user_id, ip_address, created_at DESC);

CREATE INDEX IF NOT EXISTS login_security_events_ip_idx
  ON public.login_security_events (ip_address, created_at DESC);

ALTER TABLE public.login_security_events ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.login_security_events FROM anon, authenticated;
GRANT ALL ON TABLE public.login_security_events TO service_role;

