-- Reserve a job slot atomically when a submission is created. If later rejected, release the slot.
create or replace function public.funearnezz_reserve_job_quota()
returns trigger language plpgsql security definer set search_path = '' as $$
declare
  quota_limit integer;
  occupied integer;
begin
  select j.quota,j.quota_used into quota_limit,occupied
  from public.jobs j where j.id=new.job_id and j.status='active' for update;
  if not found then raise exception 'Tugas tidak tersedia.'; end if;
  if exists (
    select 1 from public.submissions s
    where s.user_id=new.user_id and s.job_id=new.job_id and s.status in ('pending','approved')
  ) then
    raise exception 'Kamu sudah mengirim atau menyelesaikan job ini.';
  end if;
  if quota_limit is not null and occupied >= quota_limit then
    raise exception 'Kuota job sudah habis.';
  end if;
  update public.jobs set quota_used=quota_used+1 where id=new.job_id;
  return new;
end;
$$;
drop trigger if exists funearnezz_reserve_job_quota_trigger on public.submissions;
create trigger funearnezz_reserve_job_quota_trigger
before insert on public.submissions
for each row execute function public.funearnezz_reserve_job_quota();

create or replace function public.funearnezz_release_rejected_job_quota()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if old.status='pending' and new.status='rejected' then
    update public.jobs set quota_used=greatest(0,quota_used-1) where id=new.job_id;
  end if;
  return new;
end;
$$;
drop trigger if exists funearnezz_release_rejected_job_quota_trigger on public.submissions;
create trigger funearnezz_release_rejected_job_quota_trigger
after update of status on public.submissions
for each row execute function public.funearnezz_release_rejected_job_quota();

-- The user enters the full amount to deduct; DANA receives amount minus the current fee.
create or replace function public.create_withdrawal(
  p_user_id uuid, p_amount numeric, p_method text, p_destination text
) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  profile_row jsonb;
  current_balance numeric(14,2);
  disabled_account boolean;
  fee numeric(14,2) := 0;
  payout numeric(14,2);
  item public.withdrawals%rowtype;
begin
  if public.funearnezz_maintenance_enabled() then
    raise exception 'Maintenance aktif. Penarikan sementara dinonaktifkan.';
  end if;
  if p_user_id is null or p_amount is null or p_amount<=0
     or coalesce(trim(p_method),'')='' or coalesce(trim(p_destination),'')='' then
    raise exception 'Data penarikan tidak valid.';
  end if;
  if lower(trim(p_method))='dana' then
    select coalesce(nullif(value #>> '{}','')::numeric,2000) into fee
    from public.settings where key='danaFee';
    fee := coalesce(fee,2000);
  end if;
  if p_amount<=fee then raise exception 'Nominal penarikan harus lebih besar dari biaya admin DANA.'; end if;
  payout := p_amount-fee;
  select to_jsonb(p) into profile_row from public.profiles p
  where p.id=p_user_id for update;
  if profile_row is null then raise exception 'Akun tidak ditemukan.'; end if;
  disabled_account := coalesce((profile_row->>'disabled')::boolean,(profile_row->>'disable')::boolean,false);
  if disabled_account then raise exception 'Akun dinonaktifkan.'; end if;
  current_balance := coalesce((profile_row->>'balance')::numeric,0);
  if current_balance<p_amount then raise exception 'Saldo tidak mencukupi.'; end if;

  update public.profiles set balance=balance-p_amount,
    reserved_balance=coalesce(reserved_balance,0)+p_amount where id=p_user_id;
  insert into public.withdrawals(user_id,amount,method,destination,status,payout_amount,fee_amount)
  values(p_user_id,p_amount,left(trim(p_method),50),left(trim(p_destination),200),'pending',payout,fee)
  returning * into item;
  insert into public.wallet_transactions(user_id,amount,type,status,reason,reference_type,reference_id)
  values(p_user_id,-p_amount,'withdrawal_reserved','posted',
    'Penarikan menunggu pemeriksaan admin','withdrawal',item.id::text);
  return to_jsonb(item);
end;
$$;

-- Atomically redeem a code, credit the reward, write the ledger, and enforce one redemption per user/code.
create or replace function public.redeem_unique_code(p_user_id uuid,p_code text)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare
  profile_row public.profiles%rowtype;
  code_row public.unique_codes%rowtype;
  redemption public.unique_code_redemptions%rowtype;
begin
  if p_user_id is null or coalesce(trim(p_code),'')='' then raise exception 'Kode wajib diisi.'; end if;
  select * into profile_row from public.profiles where id=p_user_id for update;
  if not found or profile_row.disabled then raise exception 'Akun tidak tersedia.'; end if;
  select * into code_row from public.unique_codes
  where lower(code)=lower(trim(p_code)) for update;
  if not found then raise exception 'Unickcode tidak ditemukan.'; end if;
  if not code_row.active then raise exception 'Kode ini sudah dinonaktifkan.'; end if;
  if code_row.used_count >= code_row.max_uses then raise exception 'Kuota penerima kode sudah habis.'; end if;
  if exists(select 1 from public.unique_code_redemptions r where r.code_id=code_row.id and r.user_id=p_user_id) then
    raise exception 'Akun kamu sudah pernah memakai kode ini.';
  end if;
  update public.unique_codes set used_count=used_count+1 where id=code_row.id;
  update public.profiles set balance=balance+code_row.reward where id=p_user_id;
  insert into public.unique_code_redemptions(code_id,user_id,reward)
  values(code_row.id,p_user_id,code_row.reward) returning * into redemption;
  insert into public.wallet_transactions(user_id,amount,type,status,reason,reference_type,reference_id)
  values(p_user_id,code_row.reward,'unique_code_reward','posted',
    'Reward Unickcode '||code_row.code,'unique_code',redemption.id::text);
  return jsonb_build_object('ok',true,'reward',code_row.reward,'code',code_row.code,'used_count',code_row.used_count+1,'max_uses',code_row.max_uses);
end;
$$;

