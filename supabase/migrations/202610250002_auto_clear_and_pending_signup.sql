-- FunEarnEzz Auto Clear + pending email registration + job illustrations
-- Apply once in Supabase SQL Editor. This file is not executed by GitHub/Cloudflare.
begin;

alter table public.profiles add column if not exists email text;
alter table public.profiles add column if not exists email_verified_at timestamptz;
alter table public.profiles add column if not exists referral_code text;
alter table public.profiles add column if not exists referred_by uuid references public.profiles(id) on delete set null;

create unique index if not exists profiles_username_lower_uq on public.profiles (lower(username));
create unique index if not exists profiles_referral_code_uq on public.profiles (referral_code) where referral_code is not null;

create table if not exists public.pending_registrations (
  auth_user_id uuid primary key references auth.users(id) on delete cascade,
  email text not null,
  username text not null,
  referred_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);
create unique index if not exists pending_registrations_username_lower_uq
  on public.pending_registrations (lower(username));
create unique index if not exists pending_registrations_email_lower_uq
  on public.pending_registrations (lower(email));
create index if not exists pending_registrations_created_idx
  on public.pending_registrations (created_at);

alter table public.jobs add column if not exists illustration_path text;

create table if not exists public.auto_clear_logs (
  id bigint generated by default as identity primary key,
  run_at timestamptz not null default now(),
  trigger text not null default 'scheduled',
  deleted_chat_messages integer not null default 0,
  deleted_proof_files integer not null default 0,
  deleted_job_illustrations integer not null default 0,
  expired_registrations integer not null default 0,
  failures integer not null default 0,
  details jsonb not null default '{}'::jsonb
);
create index if not exists auto_clear_logs_run_at_idx on public.auto_clear_logs(run_at desc);

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('job-illustrations', 'job-illustrations', true, 2097152, array['image/jpeg','image/png','image/webp'])
on conflict (id) do update set public = true, file_size_limit = 2097152,
  allowed_mime_types = array['image/jpeg','image/png','image/webp'];

alter table public.pending_registrations enable row level security;
alter table public.auto_clear_logs enable row level security;
grant all privileges on public.pending_registrations, public.auto_clear_logs to service_role;
grant usage, select on sequence public.auto_clear_logs_id_seq to service_role;

create or replace function public.complete_pending_registration(p_auth_user_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_pending public.pending_registrations%rowtype;
  v_profile public.profiles%rowtype;
begin
  select * into v_pending
  from public.pending_registrations
  where auth_user_id = p_auth_user_id
  for update;

  if not found then
    select * into v_profile from public.profiles where id = p_auth_user_id;
    if not found then raise exception 'Pendaftaran sementara tidak ditemukan'; end if;
    update public.profiles
      set email_verified_at = coalesce(email_verified_at, now()),
          email = coalesce(email, v_profile.email)
      where id = p_auth_user_id
      returning * into v_profile;
    return to_jsonb(v_profile);
  end if;

  if exists (
    select 1 from public.profiles
    where lower(username) = lower(v_pending.username)
      and id <> p_auth_user_id
  ) then
    raise exception 'Username sudah digunakan. Silakan daftar kembali dengan username lain.';
  end if;

  insert into public.profiles (
    id, username, email, email_verified_at, referral_code, referred_by,
    role, balance, reserved_balance, disabled
  ) values (
    p_auth_user_id, v_pending.username, lower(v_pending.email), now(),
    'FEZ-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 10)),
    v_pending.referred_by, 'user', 0, 0, false
  )
  on conflict (id) do update set
    email = excluded.email,
    email_verified_at = coalesce(public.profiles.email_verified_at, now())
  returning * into v_profile;

  delete from public.pending_registrations where auth_user_id = p_auth_user_id;
  return to_jsonb(v_profile);
end;
$$;

revoke all on function public.complete_pending_registration(uuid) from public, anon, authenticated;
grant execute on function public.complete_pending_registration(uuid) to service_role;

commit;
