alter table public.profiles
  add column if not exists email text,
  add column if not exists email_verified_at timestamptz,
  add column if not exists referral_code text,
  add column if not exists referred_by uuid references public.profiles(id) on delete set null,
  add column if not exists referral_awarded_at timestamptz;

create unique index if not exists profiles_email_lower_uq
  on public.profiles (lower(email)) where email is not null and length(trim(email)) > 0;
create unique index if not exists profiles_referral_code_uq
  on public.profiles (referral_code) where referral_code is not null;
create index if not exists profiles_referred_by_idx
  on public.profiles (referred_by) where referred_by is not null;

insert into public.settings(key,value) values
  ('diamondRate','0'::jsonb),
  ('diamondMin','1'::jsonb),
  ('referralInviterReward','0'::jsonb),
  ('referralInviteeReward','0'::jsonb)
on conflict (key) do nothing;

create table if not exists public.referral_events (
  id bigint generated by default as identity primary key,
  referrer_id uuid not null references public.profiles(id) on delete restrict,
  referred_user_id uuid not null references public.profiles(id) on delete restrict,
  submission_id bigint not null references public.submissions(id) on delete restrict,
  referrer_reward numeric(14,2) not null default 0 check (referrer_reward >= 0),
  invitee_reward numeric(14,2) not null default 0 check (invitee_reward >= 0),
  created_at timestamptz not null default now(),
  constraint referral_events_one_award_per_invitee unique (referred_user_id)
);
create index if not exists referral_events_referrer_created_idx
  on public.referral_events(referrer_id, created_at desc);

create table if not exists public.diamond_requests (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  diamonds integer not null check (diamonds > 0),
  ff_uid text not null check (ff_uid ~ '^[0-9]{5,20}$'),
  ff_server_id text not null default '',
  rate numeric(14,2) not null check (rate > 0),
  cost numeric(14,2) not null check (cost > 0),
  status text not null default 'pending' check (status in ('pending','completed','rejected')),
  review_note text,
  reviewed_at timestamptz,
  created_at timestamptz not null default now(),
  constraint diamond_requests_total_matches check (cost = diamonds * rate)
);
create index if not exists diamond_requests_user_created_idx
  on public.diamond_requests(user_id, created_at desc);
create index if not exists diamond_requests_status_created_idx
  on public.diamond_requests(status, created_at desc);

alter table public.referral_events enable row level security;
alter table public.diamond_requests enable row level security;
grant all privileges on public.referral_events, public.diamond_requests to service_role;
grant usage, select on all sequences in schema public to service_role;

-- Create a user's first referral reward exactly once, after a job is approved.
-- Both parties must have a real profile; the invitee must be email-verified.
create or replace function public.funearnezz_award_referral_after_first_job()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  invitee public.profiles%rowtype;
  referrer public.profiles%rowtype;
  inviter_reward numeric(14,2) := 0;
  invitee_reward numeric(14,2) := 0;
  event_id bigint;
begin
  if not (old.status = 'pending' and new.status = 'approved') then
    return new;
  end if;

  select * into invitee
  from public.profiles
  where id = new.user_id
  for update;

  if not found
     or invitee.email_verified_at is null
     or invitee.referred_by is null
     or invitee.referral_awarded_at is not null then
    return new;
  end if;

  select * into referrer
  from public.profiles
  where id = invitee.referred_by
    and id <> invitee.id
    and disabled = false
  for update;

  if not found then
    return new;
  end if;

  select coalesce(nullif(value #>> '{}','')::numeric,0)
    into inviter_reward
  from public.settings where key = 'referralInviterReward';
  select coalesce(nullif(value #>> '{}','')::numeric,0)
    into invitee_reward
  from public.settings where key = 'referralInviteeReward';

  inviter_reward := greatest(0, coalesce(inviter_reward,0));
  invitee_reward := greatest(0, coalesce(invitee_reward,0));

  insert into public.referral_events(
    referrer_id, referred_user_id, submission_id, referrer_reward, invitee_reward
  )
  values(referrer.id, invitee.id, new.id, inviter_reward, invitee_reward)
  on conflict (referred_user_id) do nothing
  returning id into event_id;

  if event_id is null then
    return new;
  end if;

  if invitee_reward > 0 then
    update public.profiles set balance = balance + invitee_reward where id = invitee.id;
    insert into public.wallet_transactions(
      user_id, amount, type, status, reason, reference_type, reference_id
    ) values (
      invitee.id, invitee_reward, 'referral_reward', 'posted',
      'Bonus referral setelah email terverifikasi dan job pertama disetujui',
      'referral', event_id::text
    );
  end if;

  if inviter_reward > 0 then
    update public.profiles set balance = balance + inviter_reward where id = referrer.id;
    insert into public.wallet_transactions(
      user_id, amount, type, status, reason, reference_type, reference_id
    ) values (
      referrer.id, inviter_reward, 'referral_reward', 'posted',
      'Bonus mengundang pengguna baru yang memenuhi syarat referral',
      'referral', event_id::text
    );
  end if;

  update public.profiles set referral_awarded_at = now() where id = invitee.id;
  return new;
end;
$$;

drop trigger if exists funearnezz_award_referral_after_first_job_trigger on public.submissions;
create trigger funearnezz_award_referral_after_first_job_trigger
after update of status on public.submissions
for each row
when (old.status = 'pending' and new.status = 'approved')
execute function public.funearnezz_award_referral_after_first_job();

-- Server-side atomic reservation for a manual FF diamond request.
create or replace function public.create_diamond_request(
  p_user_id uuid,
  p_diamonds integer,
  p_ff_uid text,
  p_ff_server_id text,
  p_rate numeric,
  p_cost numeric
) returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  profile_row public.profiles%rowtype;
  configured_rate numeric(14,2);
  min_diamonds integer;
  item public.diamond_requests%rowtype;
begin
  if public.funearnezz_maintenance_enabled() then
    raise exception 'Maintenance aktif. Penarikan sementara dinonaktifkan.';
  end if;
  if p_user_id is null or p_diamonds is null or p_diamonds < 1
     or coalesce(trim(p_ff_uid),'') !~ '^[0-9]{5,20}$'
     or p_cost is null or p_rate is null then
    raise exception 'Data penarikan diamond FF tidak valid.';
  end if;

  select coalesce(nullif(value #>> '{}','')::numeric,0)
    into configured_rate from public.settings where key='diamondRate';
  select coalesce(nullif(value #>> '{}','')::integer,1)
    into min_diamonds from public.settings where key='diamondMin';
  configured_rate := coalesce(configured_rate,0);
  min_diamonds := greatest(1,coalesce(min_diamonds,1));
  if configured_rate < 1 then raise exception 'Penarikan diamond FF belum diaktifkan admin.'; end if;
  if p_diamonds < min_diamonds then raise exception 'Jumlah diamond di bawah batas minimum.'; end if;
  if p_rate <> configured_rate or p_cost <> (p_diamonds * configured_rate) then
    raise exception 'Harga diamond berubah. Muat ulang lalu coba lagi.';
  end if;

  select * into profile_row from public.profiles where id=p_user_id for update;
  if not found or profile_row.disabled then raise exception 'Akun tidak tersedia.'; end if;
  if profile_row.balance < p_cost then raise exception 'Saldo tidak mencukupi.'; end if;

  update public.profiles
    set balance = balance - p_cost,
        reserved_balance = coalesce(reserved_balance,0) + p_cost
    where id=p_user_id;

  insert into public.diamond_requests(user_id,diamonds,ff_uid,ff_server_id,rate,cost,status)
  values(p_user_id,p_diamonds,trim(p_ff_uid),left(coalesce(trim(p_ff_server_id),''),32),configured_rate,p_cost,'pending')
  returning * into item;

  insert into public.wallet_transactions(user_id,amount,type,status,reason,reference_type,reference_id)
  values(p_user_id,-p_cost,'diamond_reserved','posted',
    'Permintaan diamond Free Fire menunggu pengiriman manual admin','diamond',item.id::text);

  return to_jsonb(item);
end;
$$;

create or replace function public.review_diamond_request(
  p_diamond_request_id bigint,
  p_status text,
  p_note text,
  p_admin_id uuid
) returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  item public.diamond_requests%rowtype;
begin
  if p_status not in ('completed','rejected') then
    raise exception 'Status penarikan diamond tidak valid.';
  end if;
  if not exists (
    select 1 from public.profiles
    where id=p_admin_id and role='admin' and not disabled
  ) then raise exception 'Akses admin ditolak.'; end if;

  select * into item from public.diamond_requests
  where id=p_diamond_request_id for update;
  if not found then raise exception 'Permintaan diamond tidak ditemukan.'; end if;
  if item.status <> 'pending' then raise exception 'Permintaan ini sudah diperiksa.'; end if;

  if p_status='rejected' then
    update public.profiles
      set balance=balance+item.cost,
          reserved_balance=greatest(0,coalesce(reserved_balance,0)-item.cost)
      where id=item.user_id;
    insert into public.wallet_transactions(user_id,amount,type,status,reason,reference_type,reference_id)
    values(item.user_id,item.cost,'diamond_refund','posted',
      'Pengembalian saldo karena permintaan diamond ditolak: '||left(coalesce(p_note,''),500),
      'diamond',item.id::text);
  else
    update public.profiles
      set reserved_balance=greatest(0,coalesce(reserved_balance,0)-item.cost)
      where id=item.user_id;
  end if;

  update public.diamond_requests
    set status=p_status,review_note=left(coalesce(p_note,''),1000),reviewed_at=now()
    where id=item.id returning * into item;
  return to_jsonb(item);
end;
$$;

revoke all on function public.funearnezz_award_referral_after_first_job() from public, anon, authenticated;
revoke all on function public.create_diamond_request(uuid,integer,text,text,numeric,numeric) from public, anon, authenticated;
